/** GetUserDefaultUILanguage() → our four, exactly like installer.nsi §7. */
export function detectLang(): Lang {
  const raw =
    (typeof navigator !== "undefined" && (navigator.languages?.[0] || navigator.language)) || "en";
  const base = raw.toLowerCase().split("-")[0];
  if (base === "fa" || base === "pe") return "fa";
  if (base === "tr") return "tr";
  if (base === "ru" || base === "be" || base === "uk" || base === "kk") return "ru";
  return "en";
}

