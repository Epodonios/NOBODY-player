const cine = (lang: Lang) => DICTS[lang] as unknown as AlokDict;

/** ALOK-first translator with cinema-dict fallback — same voice as useT. */
export function useAlokT() {
  const lang = useSettings((s) => s.lang);
  return useCallback(
    (k: string): string =>
      ALOK_DICTS[lang][k] ?? cine(lang)[k] ?? ALOK_DICTS.en[k] ?? (DICTS.en as unknown as AlokDict)[k] ?? k,
    [lang],
  );
}
